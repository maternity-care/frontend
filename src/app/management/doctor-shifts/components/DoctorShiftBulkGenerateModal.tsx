function toDateKey(date: Date) {
  const year = date.getFullYear();
  const month = String(
    date.getMonth() + 1,
  ).padStart(2, "0");
  const day = String(
    date.getDate(),
  ).padStart(2, "0");

  return `${year}-${month}-${day}`;
}

function getNextWeekMondayDateKey() {
  const currentDate = new Date();
  const currentDay =
    currentDate.getDay();
  const daysUntilNextMonday =
    currentDay === 0
      ? 1
      : 8 - currentDay;

  currentDate.setDate(
    currentDate.getDate() +
      daysUntilNextMonday,
  );

  return toDateKey(currentDate);
}

function getCurrentWeekDateRange() {
  const currentDate = new Date();
  const currentDay = currentDate.getDay();
  const daysFromMonday =
    currentDay === 0 ? 6 : currentDay - 1;

  currentDate.setDate(
    currentDate.getDate() - daysFromMonday,
  );

  const dateFrom = toDateKey(currentDate);

  return {
    dateFrom,
    dateTo: addDaysToDateKey(dateFrom, 6),
  };
}

function isNextWeekMondayDateKey(
  value: string,
) {
  return (
    Boolean(value) &&
    value ===
      getNextWeekMondayDateKey()
  );
}

function formatLockedWeekDate(
  value?: string,
) {
  if (!value) {
    return "";
  }

  const [year, month, day] =
    value.split("-");

  if (
    !year ||
    !month ||
    !day
  ) {
    return value;
  }

  return `${day}-${month}-${year}`;
}


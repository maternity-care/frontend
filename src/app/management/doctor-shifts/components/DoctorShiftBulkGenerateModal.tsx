function addDaysToDateKey(
  dateKey: string,
  amount: number,
) {
  const date = new Date(`${dateKey}T00:00:00`);
  date.setDate(date.getDate() + amount);

  const year = date.getFullYear();
  const month = String(
    date.getMonth() + 1,
  ).padStart(2, "0");
  const day = String(date.getDate()).padStart(
    2,
    "0",
  );

  return `${year}-${month}-${day}`;
}


function isRecord(
  value: unknown,
): value is Record<string, unknown> {
  return (
    value !== null &&
    typeof value === "object" &&
    !Array.isArray(value)
  );
}

function getWeeklyDraftStorageKey(
  facilityId: string,
) {
  return `${WEEKLY_DRAFT_STORAGE_PREFIX}:${facilityId}`;
}

function readWeeklyDraft(
  facilityId: string,
  expectedFromDate: string,
): BulkGenerateFormValues | null {
  if (
    typeof window === "undefined" ||
    !facilityId
  ) {
    return null;
  }

  const storageKey =
    getWeeklyDraftStorageKey(
      facilityId,
    );

  try {
    const rawValue =
      window.localStorage.getItem(
        storageKey,
      );

    if (!rawValue) {
      return null;
    }

    const parsed: unknown =
      JSON.parse(rawValue);

    if (
      !isRecord(parsed) ||
      parsed.version !== 1 ||
      !isRecord(parsed.values)
    ) {
      window.localStorage.removeItem(
        storageKey,
      );
      return null;
    }

    const values =
      parsed.values;

    if (
      values.facilityId !==
        facilityId ||
      values.fromDate !==
        expectedFromDate ||
      !Array.isArray(
        values.slotGroups,
      )
    ) {
      window.localStorage.removeItem(
        storageKey,
      );
      return null;
    }

    return values as unknown as
      BulkGenerateFormValues;
  } catch {
    window.localStorage.removeItem(
      storageKey,
    );
    return null;
  }
}

function saveWeeklyDraft(
  values: BulkGenerateFormValues,
) {
  if (
    typeof window === "undefined" ||
    !values.facilityId ||
    !values.fromDate
  ) {
    return;
  }

  const draft: BulkGenerateDraft = {
    version: 1,
    savedAt:
      new Date().toISOString(),
    values,
  };

  window.localStorage.setItem(
    getWeeklyDraftStorageKey(
      values.facilityId,
    ),
    JSON.stringify(draft),
  );
}

function clearWeeklyDraft(
  facilityId: string,
) {
  if (
    typeof window === "undefined" ||
    !facilityId
  ) {
    return;
  }

  window.localStorage.removeItem(
    getWeeklyDraftStorageKey(
      facilityId,
    ),
  );
}

function mergeDraftSlotGroups(
  slots: ShiftSlotLookupItem[],
  draft:
    | BulkGenerateFormValues
    | null,
): BulkSlotGroupFormValue[] {
  const draftBySlotId =
    new Map(
      (draft?.slotGroups ?? [])
        .filter(
          (group) =>
            Boolean(group?.slotId),
        )
        .map((group) => [
          group.slotId,
          group,
        ]),
    );

  return slots.map((slot) => ({
    slotId: slot.id,
    assignments:
      draftBySlotId.get(slot.id)
        ?.assignments ?? [],
  }));
}


function getResponseMessage(
  raw: unknown,
  fallback: string,
) {
  if (!isRecord(raw)) return fallback;

  if (typeof raw.message === "string") {
    return raw.message;
  }

  if (
    isRecord(raw.data) &&
    typeof raw.data.message === "string"
  ) {
    return raw.data.message;
  }

  return fallback;
}


type BulkGenerationIssue = {
  source: "conflict" | "skipped";
  slotAssignmentIndex: number;
  assignmentIndex: number;
  shiftDate: string;
  startTime: string;
  endTime: string;
  staffId: string;
  roomId: string;
  reason: string;
  hasDoctorConflict: boolean;
  hasRoomConflict: boolean;
};

type BulkGenerationResult = {
  recognized: boolean;
  canConfirm?: boolean;
  allOrNothingRejected: boolean;
  totalCandidates: number;
  valid: number;
  skipped: number;
  conflicted: number;
  createdCount: number;
  issues: BulkGenerationIssue[];
};

function readNumberValue(
  value: unknown,
  fallback = 0,
) {
  const parsed = Number(value);

  return Number.isFinite(parsed)
    ? parsed
    : fallback;
}

function readStringValue(value: unknown) {
  return typeof value === "string"
    ? value.trim()
    : "";
}

function readRecordArray(value: unknown) {
  return Array.isArray(value)
    ? value.filter(isRecord)
    : [];
}

function readBulkGenerationResult(
  raw: unknown,
): BulkGenerationResult {
  const rawRecord = isRecord(raw)
    ? raw
    : {};

  const root =
    isRecord(rawRecord.data) &&
    (
      "summary" in rawRecord.data ||
      "conflictItems" in rawRecord.data ||
      "skippedItems" in rawRecord.data ||
      "createdCount" in rawRecord.data
    )
      ? rawRecord.data
      : rawRecord;

  const summary = isRecord(root.summary)
    ? root.summary
    : {};

  const conflictItems =
    readRecordArray(root.conflictItems);
  const skippedItems =
    readRecordArray(root.skippedItems);

  function parseIssue(
    issue: Record<string, unknown>,
    source: BulkGenerationIssue["source"],
  ): BulkGenerationIssue {
    const candidate = isRecord(
      issue.candidate,
    )
      ? issue.candidate
      : {};

    const doctorConflicts =
      readRecordArray(
        issue.doctorConflicts,
      );
    const roomConflicts =
      readRecordArray(
        issue.roomConflicts,
      );

    return {
      source,
      slotAssignmentIndex:
        readNumberValue(
          issue.slotAssignmentIndex ??
            candidate.slotAssignmentIndex,
          -1,
        ),
      assignmentIndex:
        readNumberValue(
          issue.assignmentIndex ??
            candidate.assignmentIndex,
          -1,
        ),
      shiftDate:
        readStringValue(
          issue.shiftDate ??
            candidate.shiftDate,
        ),
      startTime:
        readStringValue(
          candidate.startTime ??
            issue.startTime,
        ),
      endTime:
        readStringValue(
          candidate.endTime ??
            issue.endTime,
        ),
      staffId:
        readStringValue(
          candidate.staffId ??
            issue.staffId,
        ),
      roomId:
        readStringValue(
          candidate.roomId ??
            issue.roomId,
        ),
      reason:
        readStringValue(
          issue.reason ??
            issue.message,
        ) ||
        (
          source === "conflict"
            ? "Ca trực bị trùng lịch."
            : "Ca trực không thể được tạo."
        ),
      hasDoctorConflict:
        doctorConflicts.length > 0 ||
        Boolean(
          issue.doctorConflict ??
            issue.hasDoctorConflict,
        ),
      hasRoomConflict:
        roomConflicts.length > 0 ||
        Boolean(
          issue.roomConflict ??
            issue.hasRoomConflict,
        ),
    };
  }

  const recognized =
    "summary" in root ||
    "canConfirm" in root ||
    "allOrNothingRejected" in root ||
    "createdCount" in root ||
    "conflictItems" in root ||
    "skippedItems" in root;

  return {
    recognized,
    canConfirm:
      typeof root.canConfirm ===
      "boolean"
        ? root.canConfirm
        : undefined,
    allOrNothingRejected:
      root.allOrNothingRejected ===
      true,
    totalCandidates:
      readNumberValue(
        summary.totalCandidates,
      ),
    valid:
      readNumberValue(summary.valid),
    skipped:
      readNumberValue(
        summary.skipped,
        skippedItems.length,
      ),
    conflicted:
      readNumberValue(
        summary.conflicted,
        conflictItems.length,
      ),
    createdCount:
      readNumberValue(
        root.createdCount,
        Array.isArray(
          root.createdShifts,
        )
          ? root.createdShifts.length
          : 0,
      ),
    issues: [
      ...conflictItems.map(
        (issue) =>
          parseIssue(
            issue,
            "conflict",
          ),
      ),
      ...skippedItems.map(
        (issue) =>
          parseIssue(
            issue,
            "skipped",
          ),
      ),
    ],
  };
}

function formatIssueDate(value: string) {
  const [
    year,
    month,
    day,
  ] = value.split("-");

  if (!year || !month || !day) {
    return value || "Không rõ ngày";
  }

  return `${day}/${month}/${year}`;
}

function formatIssueTime(value: string) {
  return value
    ? value.slice(0, 5)
    : "";
}

